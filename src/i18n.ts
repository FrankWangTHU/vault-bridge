export type Language = 'zh-CN' | 'en';
export type LanguagePreference = 'auto' | Language;
export type TranslationKey = keyof typeof english;
export type Translator = (key: TranslationKey, ...args: unknown[]) => string;

export function resolveLanguage(preference: unknown, obsidianLanguage: string): Language {
  if (preference === 'en' || preference === 'zh-CN') return preference;
  return /^zh(?:[-_]|$)/i.test(obsidianLanguage) ? 'zh-CN' : 'en';
}
export function createTranslator(language: Language): Translator {
  return (key, ...args) => (language === 'en' ? english[key] : key)
    .replace(/\{(\d+)\}/g, (placeholder, index: string) => Number(index) < args.length ? String(args[Number(index)]) : placeholder);
}

// Keep error arguments structured so paths and user content are never translated.
export class LocalizedError extends Error {
  constructor(readonly key: TranslationKey, ...args: unknown[]) {
    super(createTranslator('zh-CN')(key, ...args));
    this.values = args;
  }
  readonly values: unknown[];
  localized(t: Translator): string { return t(this.key, ...this.values); }
}
export class RollbackError extends Error {
  constructor(readonly original: unknown, readonly files: string[]) {
    super(''); this.message = this.localized(createTranslator('zh-CN'));
  }
  localized(t: Translator): string {
    return formatError(this.original, t) + (this.files.length
      ? t('；部分新文件未能清理，请检查：{0}', this.files.join(', '))
      : t('；本次已写入文件已回滚。'));
  }
}
export function formatError(error: unknown, t: Translator): string {
  return error instanceof LocalizedError || error instanceof RollbackError
    ? error.localized(t) : error instanceof Error ? error.message : String(error);
}
